export const EXERCISES: Exercise[] = BASE_EXERCISES.map((exercise) => {
  const media = EXERCISE_IMAGES[exercise.id];
  return {
    ...exercise,
    imageUrl: media ? assetUrl(media.image) : undefined,
    imageUrl2: media?.image2 ? assetUrl(media.image2) : undefined,
  };
});

export const EXERCISE_MAP: Record<string, Exercise> = EXERCISES.reduce(
  (acc, exercise) => {
    acc[exercise.id] = exercise;
    return acc;
  },
  {} as Record<string, Exercise>,
);

export function formatTarget(exercise: Exercise, reps: number): string {
  return exercise.unit === 'time' ? `${reps} 秒` : `${reps} 次`;
}
